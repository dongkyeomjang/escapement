#!/usr/bin/env bash
# One serving lifecycle for the 2026-10-08 directive (DX_PREREG.md): identical to
# run_multiturn.sh (same server arguments, runner, streaming, stop by own PID)
# plus the steptime observation switch.
#
#   run_dx_lifecycle.sh <RUN_DIR_ABS> <TAG> <ARTIFACT_ABS> <PLAN_ABS> <stream|nostream> <OBS 0|1> [EVAL_S]
#
# OBS=1 exports CONTINUUM_OBS_STEPTIME=1 to the server (one [STEPTIME] line per
# step, patches/vllm_rbln-0.11.1/STEPTIME.md); OBS=0 leaves it unset.
#
# All paths absolute (KNOWN_PITFALLS 1). The server is stopped by the PID this
# script started, never by pattern (KNOWN_PITFALLS 2). Do not edit this file
# while a batch that calls it is running (KNOWN_PITFALLS 5).
set -uo pipefail

RUN="$1"; TAG="$2"; ARTIFACT="$3"; PLAN="$4"; MODE="$5"; OBS="$6"; EVAL_S="${7:-}"
case "$OBS" in 0|1) ;; *) echo "$TAG: OBS must be 0 or 1"; exit 64 ;; esac
REPO=/home/rebel/continuum-npu
cd "$REPO"
for p in "$RUN" "$ARTIFACT" "$PLAN"; do
  case "$p" in /*) ;; *) echo "$TAG: path not absolute: $p"; exit 64 ;; esac
done
DONE_MARK="$RUN/done.${TAG}"
if [ -f "$DONE_MARK" ]; then echo "$TAG already done, skipping"; exit 0; fi
mkdir -p "$RUN/probe/$TAG"

case "$MODE" in
  stream) EXTRA="--stream" ;;
  nostream) EXTRA="" ;;
  *) echo "$TAG: unknown mode $MODE"; exit 64 ;;
esac
if [ -n "$EVAL_S" ]; then EXTRA="$EXTRA --eval-s $EVAL_S"; fi

{
  echo "tag=$TAG"; echo "artifact=$ARTIFACT"; echo "plan=$PLAN"; echo "mode=$MODE"
  echo "git_head=$(git rev-parse HEAD)"
  echo "rbln_config_sha256=$(sha256sum "$ARTIFACT/rbln_config.json" | cut -d' ' -f1)"
  echo "plan_sha256=$(sha256sum "$PLAN" | cut -d' ' -f1)"
  echo "started=$(date -Is)"
  bash patches/vllm_rbln-0.11.1/apply.sh status 2>&1 | sed 's/^/patch: /'
  bash patches/vllm_rbln-0.11.1/apply_steptime.sh status 2>&1 | sed 's/^/patch-steptime: /'
  echo "obs_steptime=$OBS"
} > "$RUN/probe/$TAG/lifecycle.txt"

if [ "$OBS" = "1" ]; then OBSENV="CONTINUUM_OBS_STEPTIME=1"; else OBSENV="CONTINUUM_OBS_STEPTIME="; fi
env -u PYTHONPATH -u CONTINUUM_OBS_STEPTIME $OBSENV VLLM_LOGGING_LEVEL=DEBUG VLLM_RBLN_METRICS=1 \
  vllm serve "$ARTIFACT" \
  --host 127.0.0.1 --port 8000 \
  --enable-prefix-caching --enable-prompt-tokens-details \
  > "$RUN/server-${TAG}.log" 2>&1 &
SRV=$!

code=""
for i in $(seq 1 300); do
  code=$(curl -s -o /dev/null -w "%{http_code}" http://127.0.0.1:8000/health 2>/dev/null)
  [ "$code" = "200" ] && break
  kill -0 "$SRV" 2>/dev/null || { echo "$TAG: server died"; exit 1; }
  sleep 1
done
[ "$code" = "200" ] || { echo "$TAG: health timeout"; kill -TERM "$SRV"; exit 1; }
echo "server_ready=$(date -Is)" >> "$RUN/probe/$TAG/lifecycle.txt"

env -u PYTHONPATH "$REPO/experiments/npu/launch/run_isolated_python.sh" \
  experiments/npu/stage3/multiturn_runner.py \
  --base-url http://127.0.0.1:8000 \
  --tokenizer-dir "$ARTIFACT" --plan "$PLAN" --label "$TAG" \
  --output-dir "$RUN/probe/$TAG" $EXTRA > "$RUN/probe-${TAG}.log" 2>&1
PE=$?

curl -s http://127.0.0.1:8000/metrics > "$RUN/metrics-${TAG}.prom"

kill -TERM "$SRV" 2>/dev/null
for i in $(seq 1 60); do kill -0 "$SRV" 2>/dev/null || break; sleep 1; done
if kill -0 "$SRV" 2>/dev/null; then
  kill -KILL "$SRV" 2>/dev/null
  sleep 5
  echo "$TAG: server needed SIGKILL"
fi
wait "$SRV" 2>/dev/null
echo "finished=$(date -Is) runner_exit=$PE" >> "$RUN/probe/$TAG/lifecycle.txt"

[ "$PE" -eq 0 ] && date -Is > "$DONE_MARK"
echo "$TAG done (runner exit $PE)"
